export function t(key, idioma = 'es') {
  return strings[idioma]?.[key] || strings.es[key] || key;
}

export function getNombre(obj, idioma = 'es') {
  if (!obj?.nombre) return '';
  if (typeof obj.nombre === 'string') return obj.nombre;
  return obj.nombre[idioma] || obj.nombre.es || '';
}
